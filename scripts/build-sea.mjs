#!/usr/bin/env node
// Build simt-dev as a single-file executable (Node SEA) for the release targets.
//
// Pipeline:
//   1. collect the shipped file set (package.json `files` + package.json)
//   2. embed it as base64 in a bootstrap script; the bootstrap materializes the
//      set into ${XDG_CACHE_HOME:-$HOME/.cache}/simt-dev/v<node>/<digest>/ and
//      imports bin/simt.mjs from there, so the real tool runs with real files at
//      real paths and every import.meta.url root computation works unmodified
//   3. node --experimental-sea-config produces one blob (it embeds the bootstrap
//      source, not architecture-specific bytes); postject injects it into a
//      pinned official node binary for each target (postject is a build
//      dependency only — it is installed here, never added to package.json)
//   4. darwin binaries are ad-hoc codesigned with a fixed identifier (LIEF
//      strips the signature; without the identifier the path leaks into it)
//   5. emit dist/simt-dev-<version>-<target> + .sha256
//
// The pipeline is deterministic per build-host family: pinned node base,
// relative-path blob, fixed-identifier signature — the same tree rebuilt on
// the same OS family hashes identically (ADR-099). It is NOT byte-identical
// across host families: a darwin-generated SEA blob and a linux-generated one
// of the same tree differ, which is why each target builds on its native
// runner and the release verifies served bytes instead of comparing hosts.
//
// Usage: node scripts/build-sea.mjs [--target darwin-arm64 ...]

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { chmod, cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { TARGETS, assetName } from '../src/distribute/release.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const DIST = path.join(ROOT, 'dist');
const CACHE = path.join(ROOT, '.sea-cache');

const NODE_VERSION = 'v22.20.0'; // must equal the engines floor in package.json
const POSTJECT_VERSION = '1.0.0-alpha.6';
const FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

const pkg = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

// ---------------------------------------------------------------------------
// Payload
// ---------------------------------------------------------------------------

async function collectPayload() {
  const entries = new Map(); // relpath -> Buffer
  for (const entry of pkg.files) {
    const abs = path.join(ROOT, entry);
    const s = await stat(abs);
    if (s.isDirectory()) {
      const stack = [abs];
      while (stack.length) {
        const dir = stack.pop();
        for (const name of readDirSyncSorted(dir)) {
          const p = path.join(dir, name);
          const st = await stat(p);
          if (st.isDirectory()) stack.push(p);
          else entries.set(path.relative(ROOT, p).split(path.sep).join('/'), await readFile(p));
        }
      }
    } else {
      entries.set(entry, await readFile(abs));
    }
  }
  // package.json itself is always part of the payload (the entry computes its
  // version from it), even though `files` does not list it explicitly.
  entries.set('package.json', await readFile(path.join(ROOT, 'package.json')));
  return [...entries].sort(([a], [b]) => a.localeCompare(b));
}

function readDirSyncSorted(dir) {
  return readdirSync(dir).sort();
}

function payloadDigest(entries) {
  // Canonical form: JSON of [relpath, base64] pairs, sorted. The bootstrap
  // recomputes the same digest from its embedded entries, so the two can never
  // drift apart.
  const canonical = JSON.stringify(entries.map(([relpath, buf]) => [relpath, buf.toString('base64')]));
  return createHash('sha256').update(canonical).digest('hex');
}

// ---------------------------------------------------------------------------
// Bootstrap
// ---------------------------------------------------------------------------

function renderBootstrap(digest, entries) {
  const embedded = entries
    .map(([relpath, buf]) => `  [ ${JSON.stringify(relpath)}, ${JSON.stringify(buf.toString('base64'))} ],`)
    .join('\n');
  return `// simt-dev single-file bootstrap. Generated by scripts/build-sea.mjs — do not edit.
// Node v22 runs the SEA entry as CommonJS, so this is CJS even though the tool
// itself is ESM: it materializes the shipped file set into a per-node-version,
// per-digest cache directory, then dynamically imports the real entry point.
// The tool runs with real files at real paths, so every import.meta.url root
// computation in src/ works unmodified.
'use strict';
const { chmod, mkdir, readFile, rename, rm, writeFile } = require('node:fs/promises');
const { tmpdir } = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const DIGEST = ${JSON.stringify(digest)};
const EMBEDDED = [
${embedded}
];

function cacheRoot() {
  const base = process.env.XDG_CACHE_HOME || path.join(process.env.HOME ?? tmpdir(), '.cache');
  return path.join(base, 'simt-dev');
}

async function materialize() {
  const dir = path.join(cacheRoot(), process.version, DIGEST);
  try {
    const marker = await readFile(path.join(dir, '.digest'), 'utf8');
    if (marker.trim() === DIGEST) return dir;
  } catch {}
  await rm(dir, { recursive: true, force: true }); // stale or partial materialization
  const staging = path.join(cacheRoot(), '.materializing-' + process.pid + '-' + Date.now());
  await rm(staging, { recursive: true, force: true });
  for (const [relpath, b64] of EMBEDDED) {
    const file = path.join(staging, relpath);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, Buffer.from(b64, 'base64'));
  }
  await chmod(path.join(staging, 'bin', 'simt.mjs'), 0o755);
  await writeFile(path.join(staging, '.digest'), DIGEST + '\\n');
  await mkdir(path.dirname(dir), { recursive: true });
  await rename(staging, dir); // same parent directory: always the same filesystem, so atomic
  return dir;
}

materialize()
  .then((dir) => import(pathToFileURL(path.join(dir, 'bin', 'simt.mjs'))))
  .catch((err) => {
    console.error('simt-dev: failed to materialize the tool from the embedded payload');
    console.error(String(err && err.stack || err));
    process.exit(1);
  });
`;
}

// ---------------------------------------------------------------------------
// Base node + postject
// ---------------------------------------------------------------------------

async function ensureNodeBinary(target) {
  const file = path.join(CACHE, `node-${NODE_VERSION}-${target}`, 'bin', 'node');
  if (await exists(file)) return file;
  const dir = path.join(CACHE, `node-${NODE_VERSION}-${target}`);
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
  const tarball = path.join(CACHE, `node-${NODE_VERSION}-${target}.tar.xz`);
  const url = `https://nodejs.org/dist/${NODE_VERSION}/node-${NODE_VERSION}-${target}.tar.xz`;
  console.log(`  downloading ${url}`);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`node download failed: ${res.status} ${url}`);
  await writeFile(tarball, Buffer.from(await res.arrayBuffer()));
  // Extract the whole tree: member selection is unreliable across bsdtar/GNU tar.
  execFileSync('tar', ['-xJf', tarball, '--strip-components=1', '-C', dir]);
  if (!(await exists(file))) throw new Error('node binary missing after extraction');
  return file;
}

async function ensurePostject() {
  const deps = path.join(CACHE, 'deps');
  const postject = path.join(deps, 'node_modules', 'postject', 'dist', 'api.js');
  if (await exists(postject)) return postject;
  await mkdir(deps, { recursive: true });
  console.log(`  installing build-only dependency postject@${POSTJECT_VERSION}`);
  execFileSync('npm', ['install', '--prefix', deps, '--no-save', '--no-audit', '--no-fund', `postject@${POSTJECT_VERSION}`], { stdio: 'inherit' });
  return postject;
}

// ---------------------------------------------------------------------------
// Per-target build
// ---------------------------------------------------------------------------

async function buildTarget(target, blobBuffer) {
  const out = path.join(DIST, assetName(pkg.version, target));
  console.log(`\n=== ${target} ===`);
  const base = await ensureNodeBinary(target);
  const postjectEntry = await ensurePostject();
  const { inject } = await import(pathToFileURL(postjectEntry));

  await mkdir(DIST, { recursive: true });
  await cp(base, out);
  console.log('  injecting SEA blob');
  await inject(out, 'NODE_SEA_BLOB', blobBuffer, { machoSegmentName: 'NODE_SEA', sentinelFuse: FUSE });

  if (target.startsWith('darwin')) {
    console.log('  codesigning (ad-hoc)');
    // An explicit identifier: without one, codesign derives it from the file
    // path and embeds it in the signature, so two checkouts of the same tree
    // would produce different bytes. With a fixed identifier the ad-hoc
    // signature is deterministic, which keeps the published asset reproducible.
    execFileSync('codesign', ['--force', '-s', '-', '--identifier', 'simt-dev', out], { stdio: 'inherit' });
  }
  await chmod(out, 0o755);

  const hash = createHash('sha256').update(await readFile(out)).digest('hex');
  await writeFile(out + '.sha256', `${hash}  ${path.basename(out)}\n`);
  console.log(`  ${path.basename(out)}  sha256 ${hash.slice(0, 16)}…`);
}

async function exists(p) {
  try { await stat(p); return true; } catch { return false; }
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

const args = process.argv.slice(2);
const targets = args.filter((a) => !a.startsWith('--'));
for (const t of targets) {
  if (!TARGETS.includes(t)) {
    console.error(`unknown target ${t}; the release builds: ${TARGETS.join(', ')}`);
    process.exit(1);
  }
}
if (targets.length === 0) targets.push(...TARGETS);

const entries = await collectPayload();
const digest = payloadDigest(entries);
console.log(`payload: ${entries.length} files, digest ${digest.slice(0, 16)}…`);

// Intermediates (bootstrap, sea config, blob) live in the build cache; only
// the final binaries and their checksums land in dist/.
const BUILD = path.join(CACHE, 'build');
await mkdir(BUILD, { recursive: true });
const bootstrapFile = path.join(BUILD, 'bootstrap.cjs');
await writeFile(bootstrapFile, renderBootstrap(digest, entries));

// The SEA blob embeds the bootstrap source plus the "main" value from the
// config — version-specific, not architecture-specific. Generate it once with
// a node that runs on this host and inject the same bytes into every target's
// base. The config uses relative paths and node runs with the build dir as
// cwd, because the blob embeds "main" verbatim: an absolute path would bake
// this checkout's location into the published bytes.
const hostTarget = `${process.platform}-${process.arch}`;
if (!TARGETS.includes(hostTarget)) {
  console.error(`cannot build from this host: ${hostTarget} is not a release target (${TARGETS.join(', ')})`);
  process.exit(1);
}
const generator = await ensureNodeBinary(hostTarget);
await writeFile(path.join(BUILD, 'sea-config.json'), JSON.stringify({ main: 'bootstrap.cjs', output: 'sea-blob.bin' }));
execFileSync(generator, ['--experimental-sea-config', 'sea-config.json'], { cwd: BUILD, stdio: 'inherit' });
const blobBuffer = await readFile(path.join(BUILD, 'sea-blob.bin'));

for (const target of targets) {
  await buildTarget(target, blobBuffer);
}

console.log(`\ndone: ${targets.length} binaries in ${path.relative(ROOT, DIST)}/`);
