// The OpenCode v2 plugin this tool installs where the other harnesses get a
// config entry (opencode.ai/v2/docs/build/plugins/server, read 2026-10-29).
//
// OpenCode has no hooks file to merge into: a plugin under `.opencode/plugins/`
// is loaded as-is, so the tool owns this file's whole bytes and `rendered`
// compares them. The plugin is a thin pipe: it forwards each tool call to the
// same `agent-hook` entry point every other harness reaches, and translates
// the answer — a denial (exit 2, `{"reason": …}` on stdout) into a thrown
// error, which is how OpenCode blocks a tool call and shows the reason to the
// model. Any other outcome lets the call through: a broken policy must not
// lock a session, the same fail-open rule the shim follows.

/**
 * The plugin source for one repository.
 *
 * @param {{command: string, prompt?: boolean}} opts `command` is the
 *   `agent-hook` entry point as one line (`<binary> pre-tool-use --harness
 *   opencode`); the event word is replaced per call, so the binary and the
 *   trailing flags must each be single words. `prompt` adds the session hook
 *   that prepends the delivery packet to every prompt.
 */
export function renderOpencodePlugin({ command, prompt = false } = {}) {
  const promptHook = prompt
    ? `
    await ctx.session.hook('prompt', async (event) => {
      const result = ask('prompt-submit', { prompt: event.prompt.text, cwd: root });
      if (result.status !== 0 || !result.stdout) return;
      try {
        const packet = JSON.parse(result.stdout);
        if (packet && typeof packet.text === 'string' && packet.text) {
          event.prompt.text = \`\${packet.text}\\n\\n\${event.prompt.text}\`;
        }
      } catch {
        // a packet we cannot parse is no packet
      }
    });
`
    : '';
  return `// Generated by simt-dev — do not edit; reinstall with:
//   simt agent-hooks install --yes

import { spawnSync } from 'node:child_process';

// The entry point, one word per argument. The event is the first word after
// the binary and is replaced per call; everything after it stands for every
// event, so neither may contain a space.
const [BIN, , ...REST] = ${JSON.stringify(command)}.split(' ');

export default {
  id: 'simt-dev',
  async setup(ctx) {
    const root = ctx.location.directory;
    const ask = (event, payload) =>
      spawnSync(BIN, [event, ...REST], { input: JSON.stringify(payload), encoding: 'utf8', cwd: root });

    await ctx.tool.hook('execute.before', async (event) => {
      if (!['shell', 'write', 'edit'].includes(event.tool)) return;
      const result = ask('pre-tool-use', { tool: event.tool, input: event.input, cwd: root });
      if (result.status !== 2) return;
      let reason = 'simt-dev blocked the tool call';
      try {
        const doc = JSON.parse(result.stdout);
        if (doc && typeof doc.reason === 'string' && doc.reason) reason = doc.reason;
      } catch {
        // the default stands
      }
      throw new Error(reason);
    });
${promptHook}  },
};
`;
}
