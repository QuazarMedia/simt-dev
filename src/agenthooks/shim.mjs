// The agent-hook shim: how a harness runs this tool without it on PATH.
//
// A devDependency install puts `simt` in `node_modules/.bin`, not on a
// harness's PATH. A harness config naming the bare `simt` binary therefore
// runs nothing on Claude (a non-2 exit is silent: no enforcement) and blocks
// every tool call on Cursor (its hook fails closed). The fix is a shim beside
// the git shims, resolved the same way: `.simt-hooks/agent-hook` locates the
// dispatcher with the shared `renderLocator` block and hands over, so every
// harness config names the shim and never the bare binary (review 0003 Q21).
//
// The shim passes its own arguments through (`agent-hook "$@"`), so one file
// serves every event and every harness: the config entry decides the event and
// the `--harness` decides the dialect.

import { renderLocator } from '../locate.mjs';
import { BIN_ENV, CLI, PACKAGE_NAME } from '../name.mjs';
import { HOOKS_DIR } from '../hooks/shim.mjs';
import { localInstall } from '../distribute/release.mjs';
import { packageVersion } from '../package-version.mjs';

/** The shim inside the repository, as a harness config names it. */
export const AGENT_HOOK_SHIM = `${HOOKS_DIR}/agent-hook`;

/**
 * @param {{npm?: boolean, version?: string}} [opts]
 * @returns {string} POSIX sh source, LF-terminated, executable
 */
export function renderAgentHookShim({ npm = true, version } = {}) {
  const v = version ?? packageVersion();
  const install = npm ? `npm i -D ${PACKAGE_NAME}@${v}` : localInstall(v);
  const D = '$';
  return `#!/bin/sh
# Generated by simt-dev. Do not edit.
#
# The harness entry point: every harness config runs this file, never the bare
# \`${CLI}\` binary, because a harness does not share your shell's PATH. It only
# locates the dispatcher and hands over. Reinstall with:
# ${CLI} agent-hooks install --yes
#
# Resolution order is the git shims' order (src/locate.mjs):
#   1. ${D}SIMT_DEV_BIN    explicit override, for CI images and odd checkouts
#   2. node_modules/       the pinned project dependency
#   3. .simt/bin/          the release binary this repository downloaded
#   4. ${CLI} on PATH       a global install
# If none resolves it REFUSES rather than exiting 0.

set -eu

ROOT=\"${D}(git rev-parse --show-toplevel 2>/dev/null || pwd)\"

${renderLocator(`agent-hook \"${D}@\" --root \"${D}ROOT\"`, {
    subject: 'the agent hook',
    remedy: `REMEDY run: ${install}, or set ${BIN_ENV} to the ${CLI} binary, or remove the hook entry to opt out`,
  })}`;
}
