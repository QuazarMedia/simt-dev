// Shell completions, generated from the command registry (plan 0003 R51).
//
// The inputs are the two tables that already exist and are already checked:
// `COMMANDS` — the same list the dispatcher routes and `--help` is asserted
// against (review 0002 S15) — and the flag tables in argv.mjs. A command added
// to `IMPLEMENTED` therefore completes in all three shells with no second
// edit, which is exactly the property S15 demanded of `--help`.
//
// Deterministic by construction: every list is sorted and deduplicated before
// it is rendered, no timestamp, no host name, no environment is read. The same
// registry produces byte-identical output on any machine, so the generated
// script can be committed, diffed and reviewed like any other file.
//
// Two boundaries, both deliberate:
//
//   - Positional VALUES beyond subcommand words are file completion. The
//     registry knows words, not the skill catalogue or a path's tree, and a
//     completion that guesses is worse than one that falls back to files.
//   - bash's script stays 3.2-compatible: macOS ships /bin/bash 3.2, and a
//     completion script that fails to parse there is a silent no-op.

import { BOOL_FLAGS, VALUE_FLAGS } from './argv.mjs';

/** The shells this command can render, sorted. */
export const SHELLS = ['bash', 'fish', 'zsh'];

/** Every flag name, sorted: `--budget`, `--root`, ... Flags are global. */
const FLAGS = [...new Set([...BOOL_FLAGS, ...VALUE_FLAGS])].sort().map((f) => `--${f}`);

/** The value-flag case pattern (`--root|--task|...`), for the prev-word check. */
const VALUE_CASE = [...VALUE_FLAGS].sort().map((f) => `--${f}`).join('|');

/**
 * The registry as completions need it: the first words, and for each group the
 * subcommands under it. Derived from `commands` rather than hand-listed, so a
 * new command or subcommand arrives here without an edit.
 *
 * @param {string[]} commands sorted dispatchable paths, e.g. `['brief', 'skills index']`
 * @returns {{top: string[], groups: Array<[string, string[]]>}}
 */
export function shape(commands) {
  const top = new Set();
  const subs = new Map();
  for (const path of commands) {
    const [first, second] = path.split(' ');
    top.add(first);
    if (second !== undefined) {
      if (!subs.has(first)) subs.set(first, new Set());
      subs.get(first).add(second);
    }
  }
  return {
    top: [...top].sort(),
    groups: [...subs.entries()]
      .map(([group, set]) => [group, [...set].sort()])
      .sort((a, b) => (a[0] < b[0] ? -1 : 1)),
  };
}

/**
 * The completion script for one shell.
 *
 * @param {'bash'|'fish'|'zsh'} shell
 * @param {string[]} commands the dispatchable command paths (`COMMANDS`)
 * @returns {string} the script, newline-terminated
 */
export function renderCompletions(shell, commands) {
  const s = shape(commands);
  if (shell === 'bash') return renderBash(s);
  if (shell === 'zsh') return renderZsh(s);
  if (shell === 'fish') return renderFish(s);
  throw new Error(`unknown shell \`${shell}\`; one of: ${SHELLS.join(', ')}`);
}

function renderBash({ top, groups }) {
  const cases = groups
    .map(([group, subs]) => `      ${group}) subs='${subs.join(' ')}' ;;`)
    .join('\n');
  return [
    '# bash completion for simt. Generated by `simt completions bash`; do not edit.',
    '# Install: source <(simt completions bash), or drop it in /etc/bash_completion.d/.',
    '# bash 3.2 compatible: macOS ships /bin/bash 3.2.',
    '_simt() {',
    '  local cur prev subs flags top',
    '  cur="${COMP_WORDS[COMP_CWORD]}"',
    "  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"",
    "  subs=''",
    '',
    '  # A flag that takes a value takes a word only the shell can name: paths.',
    '  case "$prev" in',
    '    --) return 0 ;;',
    `    ${VALUE_CASE}) return 0 ;;`,
    '  esac',
    '',
    `  flags='${FLAGS.join(' ')}'`,
    `  top='${top.join(' ')}'`,
    '',
    '  case "$cur" in',
    '    -*) COMPREPLY=( $(compgen -W "$flags" -- "$cur") ); return 0 ;;',
    '  esac',
    '  if [ "$COMP_CWORD" -eq 1 ]; then',
    '    COMPREPLY=( $(compgen -W "$top" -- "$cur") )',
    '  elif [ "$COMP_CWORD" -eq 2 ]; then',
    '    case "${COMP_WORDS[1]}" in',
    cases,
    '    esac',
    '    if [ -n "$subs" ]; then',
    '      COMPREPLY=( $(compgen -W "$subs" -- "$cur") )',
    '    fi',
    '  fi',
    '}',
    'complete -o bashdefault -o default -F _simt simt',
    '',
  ].join('\n');
}

function renderZsh({ top, groups }) {
  const cases = groups
    .map(([group, subs]) => `    ${group}) subs=( ${subs.join(' ')} ) ;;`)
    .join('\n');
  return [
    '#compdef simt',
    '# zsh completion for simt. Generated by `simt completions zsh`; do not edit.',
    '# Install: save as `_simt` in a directory on $fpath and run `compinit`, or',
    '# source this after compinit: `source <(simt completions zsh)`.',
    '_simt() {',
    '  local cur prev',
    // compsys sets `words` and `CURRENT` before the function runs; without the
    // assignment `cur` and `prev` stay empty, so the flag and value-flag cases
    // below never match and zsh completes only positionals (review 0003 Q51).
    '  cur=${words[CURRENT]}',
    '  prev=${words[CURRENT-1]}',
    '  local -a top flags subs',
    `  top=( ${top.join(' ')} )`,
    `  flags=( ${FLAGS.join(' ')} )`,
    '  subs=()',
    '',
    '  # A flag that takes a value takes a word only the shell can name: paths.',
    '  case "$prev" in',
    `    --|${VALUE_CASE})`,
    '      _files',
    '      return',
    '      ;;',
    '  esac',
    '',
    '  if [[ "$cur" == -* ]]; then',
    '    compadd -- ${flags}',
    '    return',
    '  fi',
    '',
    '  case "${words[2]}" in',
    cases,
    '  esac',
    '',
    '  if (( CURRENT == 2 )); then',
    '    compadd -- ${top}',
    '  elif (( CURRENT == 3 )) && (( ${#subs} )); then',
    '    compadd -- ${subs}',
    '  else',
    '    _files',
    '  fi',
    '}',
    '',
    'if (( $+functions[compdef] )); then',
    '  compdef _simt simt',
    'fi',
    '',
  ].join('\n');
}

function renderFish({ top, groups }) {
  const level1 = top.map(
    (word) => `complete -c simt -n '__fish_use_subcommand' -a '${word}'`,
  );
  const level2 = groups.flatMap(([group, subs]) =>
    subs.map(
      (word) => `complete -c simt -n '__fish_seen_subcommand_from ${group}' -a '${word}'`,
    ),
  );
  const flagLines = FLAGS.map((flag) => {
    const name = flag.slice(2);
    return VALUE_FLAGS.has(name)
      ? `complete -c simt -l ${name} -r`
      : `complete -c simt -l ${name}`;
  });
  return [
    '# fish completion for simt. Generated by `simt completions fish`; do not edit.',
    '# Install: simt completions fish > ~/.config/fish/completions/simt.fish',
    ...level1,
    '',
    ...level2,
    '',
    ...flagLines,
    '',
  ].join('\n');
}