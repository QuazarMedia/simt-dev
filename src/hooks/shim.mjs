// Generate the POSIX sh hook shim.
//
// The shim is intentionally the smallest thing that can work: it resolves the
// dispatcher and execs it. Everything else lives in Node, where it can be
// tested. The event name is baked in at generation time rather than derived from
// `$0`, because a repo may symlink or copy `pre-push` into `pre-commit` and
// `$0` would then name the wrong hook - a silent way to run the wrong gates.
//
// POSIX sh only. ADR-012 dropped Windows, so there is exactly one code path and
// no `.cmd` shim to keep in sync.
//
// Git's own arguments are deliberately not forwarded. `pre-push` passes a remote
// name and URL, which argv would then misread as command arguments.
//
// The resolution block itself is NOT here: it is shared with the CI workflow, which
// has to find the binary by the same rules or the gate passes locally and cannot
// start in CI. See src/locate.mjs.

import { renderLocator } from '../locate.mjs';
import { BIN_ENV, CLI, MANIFEST_FILE } from '../name.mjs';

/** Events the shared dispatcher knows how to run. */
export const EVENTS = ['pre-commit', 'pre-push'];

/** Directory the shims are written to inside a repo. */
export const HOOKS_DIR = '.simt-hooks';

/** Name of the git config key that points at the shim directory. */
export const HOOKS_PATH_KEY = 'core.hooksPath';

export function fileFor(event) {
  return `${HOOKS_DIR}/${event}`;
}

/**
 * @param {string} event one of EVENTS
 * @returns {string} POSIX sh source, LF-terminated, executable
 */
export function renderShim(event) {
  if (!EVENTS.includes(event)) {
    throw new Error(`unknown hook event ${event}; known: ${EVENTS.join(', ')}`);
  }
  const D = '$';
  return `#!/bin/sh
# Generated by simt-dev. Do not edit.
#
# Every decision this hook makes is declared in ${MANIFEST_FILE}, so a reviewer reads
# the gate list in a diff instead of reverse-engineering shell. Reinstall with:
# ${CLI} hooks install --yes
#
# This file only locates the dispatcher and hands over. It resolves in order:
#   1. ${D}SIMT_DEV_BIN    explicit override, for CI images and odd checkouts
#   2. node_modules/       the pinned project dependency
#   3. simt-dev on PATH    a global install
# If none resolves it REFUSES rather than exiting 0. A hook that cannot verify
# anything must never report success - that is what teaches authors to reach for
# --no-verify.

set -eu

ROOT="${D}(git rev-parse --show-toplevel 2>/dev/null || pwd)"

${renderLocator(`hooks run ${event} --root "${D}ROOT"`, {
    subject: 'the dispatcher',
    remedy: `REMEDY set ${BIN_ENV} to the ${CLI} binary, or unset ${HOOKS_PATH_KEY} to opt out`,
  })}`;
}

/**
 * A line only a chained shim carries.
 *
 * The same reason `renderShim` bakes in its event rather than reading `$0`: a
 * shim's name cannot identify it, because the whole point of a chained shim is that
 * it is called `post-commit` because the repository called its hook that. Identity
 * has to come from the bytes, so this marker is what `hooks status` and `compare`
 * read to tell our shim from somebody else's.
 */
export const CHAIN_MARKER = '# simt-dev chain-shim: the repository hook below still runs';

/**
 * A shim for an event this tool does not gate, so the repository's own hook keeps
 * running after routing.
 *
 * `core.hooksPath` does not select a directory for the events this tool cares about
 * and leave the rest alone: git reads EVERY hook from the named directory and from
 * nowhere else. So the moment routing lands, a repository whose `post-commit` does
 * real work loses it - not loudly, because nothing failed, only silently, because
 * there is now no `post-commit` where git looks for one.
 *
 * There is nothing to enforce on such an event, so this shim does not run the
 * dispatcher at all. It runs the hook it found and forwards git's arguments, which
 * the dispatcher shim deliberately does not do: the program on the other end here is
 * the repository's own hook and expects them.
 *
 * `target` is relative to the repository's top level wherever it can be. A path
 * baked in absolute would break the first time anyone moves or clones the
 * repository somewhere else, which for a hook is the difference between a gate that
 * runs and one that stops existing.
 *
 * @param {string} event the hook event, e.g. `post-commit`. Not required to be in
 *   {@link EVENTS}: that list is what this tool gates, and chaining exists precisely
 *   for the events it does not.
 * @param {string} target the repository's hook, relative to its top level or absolute
 * @returns {string} POSIX sh source, LF-terminated, executable
 */
export function renderChainedShim(event, target) {
  const D = '$';
  return `#!/bin/sh
# Generated by simt-dev. Do not edit.
${CHAIN_MARKER}
#
# simt-dev does not gate ${event}, so nothing in this file enforces anything. It is
# here because git reads every hook from ${HOOKS_DIR} once core.hooksPath points
# there, and without this file the repository's own ${event} would stop running.
#
# It runs, in order:
#   1. ${target}
# forwarding git's arguments, which that hook expects. Reinstall with:
# ${CLI} hooks install --yes

set -eu

ROOT="${D}(git rev-parse --show-toplevel 2>/dev/null || pwd)"

TARGET='${target}'
case "${D}TARGET" in
  /*) ;;
  *) TARGET="${D}ROOT/${D}TARGET" ;;
esac

if [ ! -x "${D}TARGET" ]; then
  echo "simt: ${event} is chained to a hook that is not there." >&2
  echo "  expected: ${D}TARGET" >&2
  echo "REMEDY restore that file, or delete ${fileFor(event)} to stop chaining it." >&2
  exit 1
fi

exec "${D}TARGET" "${D}@"
`;
}