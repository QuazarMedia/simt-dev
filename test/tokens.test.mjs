// simt-dev tokens - the context meter.
//
// The fixtures are synthetic, for the reason compare.test.mjs states: the properties
// worth testing here are arithmetic and precedence, not the health of a real
// repository. What must hold for every one of them is that the numbers ADD UP - a
// meter whose channels do not sum to its total is worse than no meter, because it
// looks like evidence.
//
// Every fixture is staged inside a temp directory with no siblings, per ADR-031: a
// test that only passes because of what happens to sit next to the checkout is not a
// test of this command.

import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { after, test } from 'node:test';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';

import { tokensCommand } from '../src/commands/tokens.mjs';
import { dispatch } from '../src/commands/index.mjs';
import { plan } from '../src/projection/project.mjs';
import { buildManifest, manifestText } from '../src/projection/manifest.mjs';
import { compose } from '../src/projection/markers.mjs';
import { ALWAYS_ON_BUDGET_BYTES } from '../src/measure/context.mjs';
import { git } from './fixture.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const BIN = resolve(HERE, '..', 'bin', 'simt-dev.mjs');
const exec = promisify(execFile);
const made = [];

after(async () => {
  for (const dir of made) await rm(dir, { recursive: true, force: true });
});

async function scratch(prefix = 'simt-tokens-') {
  const dir = await mkdtemp(join(tmpdir(), prefix));
  made.push(dir);
  return dir;
}

/** A git repository with one commit: the shape every root has to be measured in. */
async function repo(parent, name) {
  const root = join(parent, name);
  await mkdir(root, { recursive: true });
  await git(['init', '-q', root]);
  await writeFile(join(root, 'README.md'), `# ${name}\n`);
  await git(['-C', root, 'add', '.']);
  await git(['-C', root, 'commit', '-qm', 'initial']);
  return root;
}

/** A manifest and the region the projection would write, the way an adopted repo looks. */
async function adopt(root, { sha = 'abc1234' } = {}) {
  const manifest = buildManifest({ root, stack: [], sha, version: '0.2.1' });
  await writeFile(join(root, 'simt-dev.json'), manifestText(manifest));
  const { targets } = await plan(root);
  await writeFile(targets[0].path, targets[0].text);
  return { manifest, region: targets[0] };
}

/** The `--json` payload of one run, straight through the binary. */
async function json(args) {
  const { stdout } = await exec('node', [BIN, 'tokens', ...args, '--json'], { maxBuffer: 16 << 20 });
  return JSON.parse(stdout);
}

/** The exit code of one run. `execFile` rejects on non-zero and never reports a code
 *  on success, so a test that asserts "it exits 0" has to read both paths or it is
 *  asserting that a promise resolved. */
async function run(args) {
  try {
    const { stdout, stderr } = await exec('node', [BIN, 'tokens', ...args], { maxBuffer: 16 << 20 });
    return { code: 0, stdout, stderr };
  } catch (error) {
    return { code: error.code, stdout: error.stdout ?? '', stderr: error.stderr ?? '' };
  }
}

test('the channels of a repository sum to its always-on total', async () => {
  // The property the whole command rests on. If a channel is measured and not
  // summed, the total is a smaller lie than any of its parts.
  const root = await repo(await scratch(), 'alpha');
  await adopt(root);

  const { stdout } = await exec('node', [BIN, 'tokens', '--root', root, '--json']);
  const payload = JSON.parse(stdout);
  assert.equal(payload.roots.length, 1);
  const row = payload.roots[0];

  assert.equal(row.adoption, 'adopted');
  assert.ok(row.generatedBytes > 0, 'an adopted repository projects a region, so it has generated bytes');

  const summed = row.channels.reduce((n, c) => n + c.generatedBytes, 0);
  assert.equal(row.generatedBytes, summed, 'the total must be the sum of the channels, not a separate number');

  // The token figure is an approximation of the same byte count, and says so by
  // construction: four bytes per token, rounded.
  assert.equal(row.generatedTokens, Math.round(row.generatedBytes / 4));
  assert.equal(payload.budget.bytesPerToken, 4);

  // And the text report must carry the number the JSON carries. Two renderings of one
  // fact that disagree is the one-question-two-answers defect (ADR-050).
  const text = await exec('node', [BIN, 'tokens', '--root', root]);
  assert.match(text.stdout, new RegExp(`always-on ${row.generatedBytes} B generated`));
  assert.match(text.stdout, new RegExp(`~${row.generatedTokens} tokens`));
});

test('a hand-written prefix is counted as read and never as generated', async () => {
  // ADR-064 ruling 2. A repository with a 6 KB hand-written AGENTS.md has a context
  // problem this tool does not have, and billing those bytes to the budget would move
  // the number the budget is about.
  const root = await repo(await scratch(), 'alpha');
  await adopt(root);
  const before = (await json(['--root', root])).roots[0];

  const handWritten = `# House rules\n\n${'Policy prose written by a person. '.repeat(120)}\n`;
  const text = await readFile(join(root, 'AGENTS.md'), 'utf8');
  await writeFile(join(root, 'AGENTS.md'), `${handWritten}\n${text}`);

  const after_ = (await json(['--root', root])).roots[0];
  assert.equal(after_.generatedBytes, before.generatedBytes, 'the generated bytes cannot move');
  assert.ok(
    after_.readerBytes - after_.generatedBytes >= Buffer.byteLength(handWritten),
    'the hand-written bytes must appear as read bytes',
  );
  assert.equal(after_.budget.over, false);
});

test('a skill costs its name and its description, not its body', async () => {
  // The Agent Skills spec has a reader load the frontmatter to decide whether to open
  // the body. Counting the body would report a cost no turn pays.
  const root = await repo(await scratch(), 'alpha');
  await adopt(root);
  const body = 'x'.repeat(4000);
  await mkdir(join(root, '.agents', 'skills', 'demo'), { recursive: true });
  await writeFile(
    join(root, '.agents', 'skills', 'demo', 'SKILL.md'),
    `---\nname: demo\ndescription: A demo skill.\n---\n\n# Demo\n\n${body}\n`,
  );

  const row = (await json(['--root', root])).roots[0];
  const skills = row.channels.find((c) => c.channel === 'skills');
  assert.ok(skills, 'the skill channel is counted');
  assert.equal(skills.files, 1);
  // "demo" + "\n" + "A demo skill." - and nothing else.
  assert.equal(skills.generatedBytes, Buffer.byteLength('demo\nA demo skill.'));
});

test('--repos gives a later repository the paragraphs an earlier one already loaded', async () => {
  // The figure review 0002 quoted: 72% of the estate's always-on bytes were a
  // paragraph a previous root had loaded. Two repositories projected from the same
  // rules are exactly that case, and the arithmetic has to reconcile or the number is
  // decoration.
  const parent = await scratch('simt-tokens-ws-');
  const a = await repo(parent, 'repo-a');
  const b = await repo(parent, 'repo-b');
  await adopt(a);
  await adopt(b);

  const payload = await json(['--root', parent, '--repos']);
  assert.equal(payload.mode, 'repositories');
  assert.deepEqual(
    payload.roots.map((r) => r.name),
    ['repo-a', 'repo-b'],
    'roots are measured in a stable order, because the order decides who owns a shared paragraph',
  );

  const [first, second] = payload.roots;
  assert.equal(first.redundancy.duplicateBytes, 0, 'the first repository has nothing earlier to repeat');
  assert.ok(
    second.redundancy.duplicateBytes > 5000,
    `the second repository shares the projection, so most of it is duplicate (got ${second.redundancy.duplicateBytes})`,
  );
  assert.equal(second.redundancy.uniqueBytes, 0, 'two repositories projected from one corpus share every paragraph');

  const t = payload.totals;
  assert.equal(t.roots, 2);
  assert.equal(
    t.duplicateBytes,
    first.redundancy.duplicateBytes + second.redundancy.duplicateBytes,
  );
  assert.equal(t.generatedBytes, first.generatedBytes + second.generatedBytes);
  assert.equal(t.uniqueBytes + t.duplicateBytes, t.blockBytes);

  const text = await exec('node', [BIN, 'tokens', '--root', parent, '--repos']);
  assert.match(text.stdout, new RegExp(`duplicate ${t.duplicateBytes} B \\(${Math.round((t.duplicateBytes / t.generatedBytes) * 100)}% of generated\\)`));
});

test('a region past a reader`s read limit is reported with its numbers', async () => {
  // The Codex limit is a real truncation: a region ending past 32,768 B is never read.
  // S37 reports it as a check finding; the meter reports the same fact, from the same
  // function, so the two cannot disagree about who stops reading and where.
  const root = await repo(await scratch(), 'alpha');
  await adopt(root);
  const text = await readFile(join(root, 'AGENTS.md'), 'utf8');
  await writeFile(join(root, 'AGENTS.md'), `${'x'.repeat(33_000)}\n${text}`);

  const row = (await json(['--root', root])).roots[0];
  assert.equal(row.readLimits.length, 1);
  assert.equal(row.readLimits[0].reader, 'Codex');
  assert.equal(row.readLimits[0].limit, 32_768);
  assert.ok(row.readLimits[0].overBy > 0, 'the region ends past the limit it is measured against');
  assert.ok(
    row.findings.some((f) => f.includes('BEYOND-READ-LIMIT') && f.includes('Codex')),
    'the reader is named, because "the file is long" does not say who stops reading it',
  );
});

test('a region over the budget is reported and the run still succeeds', async () => {
  // The budget is a fact about a repository, not a failure of the command. A meter
  // that exited non-zero here would train people to ignore the number it prints.
  const root = await repo(await scratch(), 'alpha');
  const big = 'Long generated prose. '.repeat(1800);
  await writeFile(join(root, 'AGENTS.md'), compose(big, { sha: 'abc1234' }, 'html'));

  const payload = await json(['--root', root]);
  const row = payload.roots[0];
  assert.ok(row.generatedBytes > ALWAYS_ON_BUDGET_BYTES, 'the fixture is over budget, or the test proves nothing');
  assert.equal(row.budget.over, true);
  assert.equal(row.budget.overBy, row.generatedBytes - ALWAYS_ON_BUDGET_BYTES);
  assert.deepEqual(payload.totals.overBudget, ['alpha']);

  const { code } = await run(['--root', root]);
  assert.equal(code, 0, 'over budget is reported, not failed');
});

test('an unmanaged repository measures zero and is not an error', async () => {
  // simt-dev is deliberately not adopted into itself, so this is the shape a reader of
  // this repository actually gets: no manifest, no projection, nothing to attribute.
  const root = await repo(await scratch(), 'alpha');
  await writeFile(join(root, 'AGENTS.md'), '# Hand written, all of it.\n');

  const row = (await json(['--root', root])).roots[0];
  assert.equal(row.adoption, 'unmanaged');
  assert.equal(row.generatedBytes, 0);
  assert.ok(row.readerBytes > 0, 'the hand-written file is still read by whoever opens it');
  assert.equal(row.budget.over, false);
});

test('a directory that holds repositories says so and names both ways to measure', async () => {
  // The failure this command has is being pointed at the wrong shape of path, and the
  // remedy has to be a command, not a location (the rule this package is judged by).
  const parent = await scratch('simt-tokens-ws-');
  await repo(parent, 'repo-a');
  await repo(parent, 'repo-b');

  const failure = await run(['--root', parent]);
  assert.notEqual(failure.code, 0);
  assert.ok(failure.stderr.includes('holds repositories rather than being one'), failure.stderr);
  assert.match(failure.stderr, /tokens --root <path>/);
  assert.match(failure.stderr, /tokens --repos --root/);

  const empty = await scratch('simt-tokens-empty-');
  const noRepos = await run(['--repos', '--root', empty]);
  assert.notEqual(noRepos.code, 0);
  assert.ok(noRepos.stderr.includes('contains no git repositories'), noRepos.stderr);
});

test('the command is reachable by name, with the flag it documents', async () => {
  // The registry is the authority on what this binary can do, and `help` is generated
  // against it. A command that exists only as an import would pass every test above
  // and be unreachable by a reader.
  const root = await repo(await scratch(), 'alpha');
  await adopt(root);

  const code = await dispatch(['tokens', '--root', root, '--json']);
  assert.equal(code, 0);

  const help = await exec('node', [BIN, 'help']);
  assert.match(help.stdout, /tokens \[--repos\]/);
  assert.match(help.stdout, /--repos\s+tokens: measure every repository/);
});